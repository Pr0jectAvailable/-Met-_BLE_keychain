#!/usr/bin/env python3
"""Decrypt a backend keys CSV (age- or gpg-encrypted) for backend import.

Complements provision.py: it encrypts the plaintext CSV with the age public key
(`age1...`), the backend decrypts it with the matching private key
(`keys/age_private.key`, generated by gen_age_key.py).

Requires: age (for .age files) or gpg (for gpg-encrypted files).

    Windows: scoop install age   /   choco install age
    Linux:   apt install age

Usage:
    # decrypt with the default private key -> ./batch/backend_keys.csv
    python decrypt_keys.py --in ./batch/backend_keys.csv.age

    # explicit key and output
    python decrypt_keys.py --in ./batch/backend_keys.csv.age \
        --key ./keys/age_private.key --out ./backend_keys.csv

    # print to stdout instead of writing a file (careful: contains secrets)
    python decrypt_keys.py --in ./batch/backend_keys.csv.age --stdout

WARNING: the decrypted CSV holds every device key. Do not commit it, send it
over messengers, or leave it on disk longer than necessary.
"""

import argparse
import os
import shutil
import subprocess
import sys


DEFAULT_KEY = "./keys/age_private.key"


def decrypt_age(in_path: str, key_path: str, out_path: str | None,
                to_stdout: bool) -> None:
    exe = shutil.which("age")
    if not exe:
        raise SystemExit(
            "age not found in PATH. Install age: "
            "https://github.com/FiloSottile/age"
        )
    if not os.path.exists(key_path):
        raise SystemExit("private key not found: %s" % key_path)

    cmd = [exe, "--decrypt", "-i", key_path]
    if to_stdout:
        proc = subprocess.run(cmd + [in_path], capture_output=True)
        if proc.returncode != 0:
            sys.stderr.write(proc.stderr.decode(errors="replace"))
            raise SystemExit("age decrypt failed")
        sys.stdout.buffer.write(proc.stdout)
        return

    assert out_path is not None
    cmd += ["-o", out_path, in_path]
    proc = subprocess.run(cmd, capture_output=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr.decode(errors="replace"))
        raise SystemExit("age decrypt failed")
    print("decrypted CSV -> %s" % out_path)


def decrypt_gpg(in_path: str, out_path: str | None, to_stdout: bool) -> None:
    exe = shutil.which("gpg")
    if not exe:
        raise SystemExit("gpg not found in PATH")
    cmd = [exe, "--decrypt", "--batch", in_path]
    proc = subprocess.run(cmd, capture_output=True)
    if proc.returncode != 0:
        sys.stderr.write(proc.stderr.decode(errors="replace"))
        raise SystemExit("gpg decrypt failed")
    if to_stdout:
        sys.stdout.buffer.write(proc.stdout)
    else:
        assert out_path is not None
        with open(out_path, "wb") as f:
            f.write(proc.stdout)
        print("decrypted CSV -> %s" % out_path)


def main() -> int:
    ap = argparse.ArgumentParser(description="Decrypt backend keys CSV.")
    ap.add_argument("--in", dest="in_path", required=True,
                    help="encrypted CSV (.age or gpg)")
    ap.add_argument("--key", default=DEFAULT_KEY,
                    help="age private key (default: %s)" % DEFAULT_KEY)
    ap.add_argument("--out",
                    help="output CSV path (default: <in> without .age)")
    ap.add_argument("--stdout", action="store_true",
                    help="write decrypted CSV to stdout instead of a file")
    args = ap.parse_args()

    in_path = os.path.abspath(args.in_path)
    if not os.path.exists(in_path):
        raise SystemExit("input not found: %s" % in_path)

    out_path = None
    if not args.stdout:
        if args.out:
            out_path = os.path.abspath(args.out)
        elif in_path.endswith(".age"):
            out_path = in_path[:-4]
        else:
            out_path = in_path + ".csv"
        if os.path.exists(out_path):
            raise SystemExit("%s exists; remove it or pass a different --out"
                             % out_path)

    if in_path.endswith(".age"):
        decrypt_age(in_path, os.path.abspath(args.key), out_path, args.stdout)
    else:
        decrypt_gpg(in_path, out_path, args.stdout)

    if not args.stdout:
        print("WARNING: keep this file secret and delete it after import.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
